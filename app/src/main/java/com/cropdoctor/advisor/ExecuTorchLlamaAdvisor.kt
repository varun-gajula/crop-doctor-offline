package com.cropdoctor.advisor

import android.app.ActivityManager
import android.content.Context
import android.os.Build
import android.os.Debug
import android.util.Log
import com.cropdoctor.domain.SeverityBand
import com.cropdoctor.knowledge.KbEntry
import kotlinx.coroutines.*
import org.pytorch.executorch.LlamaCallback
import org.pytorch.executorch.LlamaModule
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * On-Device Llama 3.2 1B-Instruct Advisor powered by ExecuTorch on Arm CPU (Rule R7 & PS1).
 *
 * Enforces:
 * - Rule H6: Telugu is NEVER generated by Llama (always verified KB translations).
 * - Rule H11 & T2c: When certainty is Not sure or disease unknown, no severity reasoning.
 * - Rule H4 & H5: Grounded prompts from seed/prompt_template.txt with GuardrailFilter.
 * - Rule H15: 6 GB RAM budget. Peak app PSS <= 2.5 GB with model, <= 500 MB without.
 *   Model loaded lazily, checked against available memory, and released after 60s idle.
 * - Streaming tokens with ~100 ms UI updates, timeout, and cancellation support.
 */
class ExecuTorchLlamaAdvisor(private val context: Context) : Advisor {

    private val TAG = "ExecuTorchLlamaAdvisor"
    private val fakeAdvisor = FakeAdvisor()

    private var modelFile: File? = null
    private var tokenizerFile: File? = null

    private var llamaModule: LlamaModule? = null
    private var isModelLoaded = false
    private var idleJob: Job? = null
    private val modelLock = Any()

    override val isFake: Boolean
        get() = isEmulator() || modelFile == null || tokenizerFile == null

    init {
        findModelFiles()
    }

    fun findModelFiles() {
        // 1. Check in app's private filesDir
        val candidates = context.filesDir.listFiles()?.filter {
            it.name.endsWith(".pte") && (it.name.contains("llama", ignoreCase = true) || it.name.contains("1b", ignoreCase = true))
        } ?: emptyList()

        val appModel = candidates.maxByOrNull { it.length() } ?: File(context.filesDir, "llama-3.2-1b-spinquant.pte")
        val appTokenizer = File(context.filesDir, "tokenizer.model")

        if (appModel.exists() && appModel.length() > 50_000_000L && appTokenizer.exists() && appTokenizer.length() > 100_000L) {
            modelFile = appModel
            tokenizerFile = appTokenizer
            Log.i(TAG, "Located Llama 3.2 1B in app files: ${appModel.name} (${appModel.length() / (1024 * 1024)} MB)")
            return
        }

        // 2. Check /data/local/tmp/ fallback
        val tmpModel = File("/data/local/tmp/llama-3.2-1b-spinquant.pte")
        val tmpTokenizer = File("/data/local/tmp/tokenizer.model")
        if (tmpModel.exists() && tmpModel.length() > 50_000_000L && tmpTokenizer.exists() && tmpTokenizer.length() > 100_000L) {
            modelFile = tmpModel
            tokenizerFile = tmpTokenizer
            Log.i(TAG, "Located Llama 3.2 1B at ${tmpModel.absolutePath} (${tmpModel.length() / (1024 * 1024)} MB)")
            return
        }

        Log.i(TAG, "Llama 3.2 1B weights not found in private files or /data/local/tmp/. Using grounded KB advisor fallback.")
    }

    private fun isEmulator(): Boolean {
        return (Build.FINGERPRINT.startsWith("generic")
                || Build.FINGERPRINT.startsWith("unknown")
                || Build.MODEL.contains("google_sdk")
                || Build.MODEL.contains("Emulator")
                || Build.MODEL.contains("Android SDK built for x86")
                || Build.MANUFACTURER.contains("Genymotion")
                || (Build.BRAND.startsWith("generic") && Build.DEVICE.startsWith("generic"))
                || "google_sdk" == Build.PRODUCT
                || Build.HARDWARE.contains("goldfish")
                || Build.HARDWARE.contains("ranchu"))
    }

    private fun checkMemoryBudget(): Boolean {
        return try {
            val actManager = context.getSystemService(Context.ACTIVITY_SERVICE) as? ActivityManager ?: return true
            val memInfo = ActivityManager.MemoryInfo()
            actManager.getMemoryInfo(memInfo)
            val availMb = memInfo.availMem / (1024 * 1024)
            Log.i(TAG, "Rule H15 check: Available RAM = ${availMb} MB, LowMemory = ${memInfo.lowMemory}")
            if (memInfo.lowMemory || memInfo.availMem < 1500L * 1024L * 1024L) {
                Log.w(TAG, "Low device RAM (${availMb} MB < 1500 MB). Fallback to KB text alone (Rule H15).")
                false
            } else {
                true
            }
        } catch (e: Exception) {
            true
        }
    }

    private fun ensureModelLoaded(): Boolean {
        synchronized(modelLock) {
            if (isModelLoaded && llamaModule != null) {
                return true
            }

            val mFile = modelFile ?: return false
            val tFile = tokenizerFile ?: return false

            if (!checkMemoryBudget()) {
                return false
            }

            try {
                Log.i(TAG, "Loading Llama 3.2 1B ExecuTorch module (arm64-v8a)...")
                val startTime = System.currentTimeMillis()
                val module = LlamaModule(mFile.absolutePath, tFile.absolutePath, 0.7f)
                val status = module.load()
                val loadDurationMs = System.currentTimeMillis() - startTime
                Log.i(TAG, "LlamaModule.load() returned status $status in ${loadDurationMs} ms")

                if (status == 0) {
                    llamaModule = module
                    isModelLoaded = true
                    scheduleIdleRelease()
                    return true
                } else {
                    Log.e(TAG, "LlamaModule.load() failed with code $status")
                    return false
                }
            } catch (e: Throwable) {
                Log.e(TAG, "Failed to instantiate or load LlamaModule", e)
                return false
            }
        }
    }

    private fun scheduleIdleRelease() {
        idleJob?.cancel()
        idleJob = CoroutineScope(Dispatchers.Default).launch {
            delay(60_000L) // 60 seconds idle release (Rule H15)
            synchronized(modelLock) {
                try {
                    llamaModule?.resetNative()
                    llamaModule = null
                    isModelLoaded = false
                    System.gc()
                    Log.i(TAG, "Released Llama 3.2 1B model after 60s idle (Rule H15).")
                } catch (e: Throwable) {
                    Log.e(TAG, "Error during idle model release", e)
                }
            }
        }
    }

    override suspend fun generateAdvice(
        classId: String,
        severityBand: SeverityBand,
        certainty: String,
        language: String,
        kbEntry: KbEntry,
        onToken: (String) -> Unit
    ) = withContext(Dispatchers.Default) {
        val isNotSure = certainty.equals("NOT_SURE", ignoreCase = true) ||
                certainty.equals("Not sure", ignoreCase = true) ||
                classId.equals("unknown", ignoreCase = true)

        // RULE H11 & T2c: When certainty is Not sure or disease unknown, NEVER ask Llama to reason about severity.
        if (isNotSure) {
            fakeAdvisor.generateAdvice(classId, severityBand, certainty, language, kbEntry, onToken)
            return@withContext
        }

        // RULE H6: Telugu is NEVER generated by Llama (unsupported by Meta Llama 3.2).
        if (language.equals("te", ignoreCase = true)) {
            fakeAdvisor.generateAdvice(classId, severityBand, certainty, language, kbEntry, onToken)
            return@withContext
        }

        // Emulator check: Emulator cannot run 4-bit Arm kernels -> use FakeAdvisor
        if (isEmulator() || modelFile == null || tokenizerFile == null) {
            fakeAdvisor.generateAdvice(classId, severityBand, certainty, language, kbEntry, onToken)
            return@withContext
        }

        // Load real Llama 3.2 1B module on Arm phone
        val ready = ensureModelLoaded()
        if (!ready || llamaModule == null) {
            Log.w(TAG, "Real Llama module could not be loaded; falling back to static KB advisory")
            fakeAdvisor.generateAdvice(classId, severityBand, certainty, language, kbEntry, onToken)
            return@withContext
        }

        // Reset idle release timer
        scheduleIdleRelease()

        // Build grounded prompt adhering to seed/prompt_template.txt
        val prompt = PromptBuilder.buildPrompt(
            crop = kbEntry.crop,
            diseaseName = kbEntry.names.forLanguage(language),
            severity = severityBand.name,
            certainty = certainty,
            kbEntry = kbEntry,
            language = language
        )

        val fullTextBuilder = java.lang.StringBuilder()
        val tokenThrottleBuffer = java.lang.StringBuilder()
        var lastEmitTime = System.currentTimeMillis()
        val genStartTime = System.currentTimeMillis()
        var firstTokenTimeMs = 0L
        var totalTokens = 0

        val llamaCallback = object : LlamaCallback {
            override fun onResult(token: String?) {
                if (token.isNullOrEmpty()) return
                totalTokens++
                val now = System.currentTimeMillis()
                if (firstTokenTimeMs == 0L) {
                    firstTokenTimeMs = now - genStartTime
                }

                val sanitizedToken = GuardrailFilter.sanitize(token)
                fullTextBuilder.append(sanitizedToken)
                tokenThrottleBuffer.append(sanitizedToken)

                // Throttle UI update to ~100 ms or upon line breaks / sentence ends
                if (now - lastEmitTime >= 100L || token.contains("\n") || token.contains("।") || token.contains(".")) {
                    val chunk = tokenThrottleBuffer.toString()
                    tokenThrottleBuffer.setLength(0)
                    lastEmitTime = now
                    onToken(chunk)
                }
            }

            override fun onStats(stats: Float) {
                // Optional native execution statistics
            }
        }

        try {
            // Apply 25-second timeout safeguard
            withTimeoutOrNull(25_000L) {
                llamaModule?.generate(prompt, 128, llamaCallback, false)
            }

            // Flush any remaining buffered tokens
            if (tokenThrottleBuffer.isNotEmpty()) {
                onToken(tokenThrottleBuffer.toString())
                tokenThrottleBuffer.setLength(0)
            }

            val totalGenDurationMs = System.currentTimeMillis() - genStartTime
            val fullGeneratedText = fullTextBuilder.toString().trim()

            // Verify with GuardrailFilter (Rule H4 & H5)
            val validation = GuardrailFilter.validateAdvice(fullGeneratedText, kbEntry, severityBand)
            if (!validation.isValid) {
                Log.w(TAG, "Guardrail violation: ${validation.failureReason}. Reverting to verified KB text alone.")
                val officialKbText = "\n\n" + kbEntry.explainText.forLanguage(language) + "\n\n" + kbEntry.immediateStep.forLanguage(language)
                onToken(officialKbText)
            }

            // Log benchmark measurements (load time, first-token time, tokens/s, peak RAM)
            logBenchmarkMetrics(
                loadTimeMs = 0L,
                firstTokenTimeMs = firstTokenTimeMs,
                totalGenTimeMs = totalGenDurationMs,
                tokenCount = totalTokens,
                language = language,
                crop = kbEntry.crop,
                disease = kbEntry.names.en,
                guardrailPassed = validation.isValid
            )

        } catch (e: Exception) {
            Log.e(TAG, "Error during Llama generation", e)
            fakeAdvisor.generateAdvice(classId, severityBand, certainty, language, kbEntry, onToken)
        }
    }

    private fun logBenchmarkMetrics(
        loadTimeMs: Long,
        firstTokenTimeMs: Long,
        totalGenTimeMs: Long,
        tokenCount: Int,
        language: String,
        crop: String,
        disease: String,
        guardrailPassed: Boolean
    ) {
        try {
            val genOnlyMs = totalGenTimeMs - firstTokenTimeMs
            val tokensPerSec = if (genOnlyMs > 0) (tokenCount.toDouble() / (genOnlyMs / 1000.0)) else 0.0
            val peakRamPssMb = Debug.getPss() / 1024L

            val dateFormat = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US)
            val dateStr = dateFormat.format(Date())

            val benchDir = File(context.filesDir, "benchmarks")
            benchDir.mkdirs()

            val logFile = File(benchDir, "llama_$dateStr.json")
            val latestFile = File(benchDir, "llama_latest.json")

            val jsonContent = """
{
  "timestamp": "$dateStr",
  "device_model": "${Build.MODEL}",
  "cpu_abi": "${Build.SUPPORTED_ABIS.firstOrNull() ?: "unknown"}",
  "target_hardware": "Arm64-v8a",
  "model_name": "meta-llama/Llama-3.2-1B-Instruct",
  "quantization": "SpinQuant INT4 EO8",
  "runtime": "ExecuTorch 0.5.1",
  "crop": "$crop",
  "disease": "$disease",
  "language": "$language",
  "metrics": {
    "first_token_time_ms": $firstTokenTimeMs,
    "total_generation_time_ms": $totalGenTimeMs,
    "tokens_generated": $tokenCount,
    "tokens_per_second": ${String.format(Locale.US, "%.2f", tokensPerSec)},
    "peak_ram_pss_mb": $peakRamPssMb,
    "ram_budget_limit_mb": 2500,
    "ram_budget_compliant": ${peakRamPssMb <= 2500},
    "guardrail_passed": $guardrailPassed
  }
}
            """.trimIndent()

            logFile.writeText(jsonContent)
            latestFile.writeText(jsonContent)
            Log.i(TAG, "Benchmark logged to ${logFile.absolutePath} (Tokens/s: ${String.format(Locale.US, "%.2f", tokensPerSec)}, RAM: ${peakRamPssMb}MB)")
        } catch (e: Exception) {
            Log.e(TAG, "Failed to write llama benchmark log", e)
        }
    }

    override fun stop() {
        try {
            llamaModule?.stop()
            Log.i(TAG, "LlamaModule.stop() requested")
        } catch (e: Throwable) {
            Log.e(TAG, "Failed to stop LlamaModule", e)
        }
    }

    override fun close() {
        synchronized(modelLock) {
            try {
                idleJob?.cancel()
                llamaModule?.resetNative()
                llamaModule = null
                isModelLoaded = false
            } catch (e: Throwable) {
                Log.e(TAG, "Error closing LlamaModule", e)
            }
        }
        fakeAdvisor.close()
    }
}
