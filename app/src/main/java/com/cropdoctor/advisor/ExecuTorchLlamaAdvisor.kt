/**
 * On-Device Llama 3.2 1B-Instruct Advisor powered by ExecuTorch on Arm CPU (Rule R7 & PS1).
 *
 * Task A-REAL Enforcements:
 * - Direct lookup in app private storage (filesDir), app external storage (getExternalFilesDir),
 *   and /data/local/tmp (only if readable, reporting SELinux status).
 * - ZERO fake intelligence / simulated delay streaming in production code.
 * - If real Llama cannot run (missing weights, low memory, load failure), emits static
 *   verified Knowledge Base advice immediately with advisor_source="OFFLINE_GUIDE".
 * - When real Llama runs on-device, streams tokens with advisor_source="LLAMA".
 * - Rule H6: Telugu is NEVER generated by Llama (always verified KB translations in code).
 * - Rule H11 & T2c: When certainty is Not sure or disease unknown, no severity reasoning.
 * - Rule H4 & H5: Grounded prompts with GuardrailFilter.
 * - Rule H15: 6 GB RAM budget. Peak app PSS <= 2.5 GB with model, <= 500 MB without.
 *   Model loaded lazily, checked against available memory, and released after 60s idle.
 */
class ExecuTorchLlamaAdvisor(private val context: Context) : Advisor {

    private val TAG = "ExecuTorchLlamaAdvisor"

    private var modelFile: File? = null
    private var tokenizerFile: File? = null

    private var llamaModule: LlmModule? = null
    private var isModelLoaded = false
    val isModelCurrentlyLoaded: Boolean
        get() = isModelLoaded
    private var idleJob: Job? = null
    private val modelLock = Any()

    private val llamaDispatcher = Executors.newSingleThreadExecutor { runnable ->
        Thread(runnable, "CropDoc-LlamaWorker").apply {
            isDaemon = true
            priority = Thread.NORM_PRIORITY - 1
        }
    }.asCoroutineDispatcher()

    @Volatile
    private var isGenerating = false
    @Volatile
    private var isLoading = false
    @Volatile
    private var isStopRequested = false
    @Volatile
    private var currentActiveRequestId: Long = -1L
    private val generationLock = Mutex()

    private var _advisorSource: String = "OFFLINE_GUIDE"
    override val advisorSource: String
        get() = _advisorSource

    override val isModelAvailable: Boolean
        get() = (modelFile != null && tokenizerFile != null)

    private var _isLowMemoryFallback: Boolean = false
    override val isLowMemoryFallback: Boolean
        get() = _isLowMemoryFallback

    private var _isFallbackToOfflineGuide: Boolean = false
    override val isFallbackToOfflineGuide: Boolean
        get() = _isFallbackToOfflineGuide || _isLowMemoryFallback

    var memoryThresholdBytes: Long = MemoryBudgetDecider.MIN_AVAILABLE_RAM_BYTES

    override val isFake: Boolean
        get() = modelFile == null || tokenizerFile == null

    init {
        findModelFiles()
    }

    fun getResolvedModelPath(): String? = modelFile?.absolutePath
    fun getResolvedTokenizerPath(): String? = tokenizerFile?.absolutePath

    fun findModelFiles() {
        Log.i(TAG, "findModelFiles() scanning for Llama 3.2 1B weights...")

        val extFilesDir = context.getExternalFilesDir(null)

        // 1. Discover all candidate model files (> 50 MB)
        val internalCandidates = context.filesDir.listFiles()?.filter {
            it.name.endsWith(".pte") && (it.name.contains("llama", ignoreCase = true) || it.name.contains("1b", ignoreCase = true) || it.name.contains("spinquant", ignoreCase = true))
        } ?: emptyList()

        val extCandidates = if (extFilesDir != null && extFilesDir.exists()) {
            extFilesDir.listFiles()?.filter {
                it.name.endsWith(".pte") && (it.name.contains("llama", ignoreCase = true) || it.name.contains("1b", ignoreCase = true) || it.name.contains("spinquant", ignoreCase = true))
            } ?: emptyList()
        } else emptyList()

        val allModelCandidates = (internalCandidates + extCandidates).filter { it.exists() && it.canRead() && it.length() > 50_000_000L }
        var chosenModel = allModelCandidates.maxByOrNull { it.length() }

        // 2. Discover all candidate tokenizer files (> 50 KB)
        val candidateTokenizers = listOfNotNull(
            File(context.filesDir, "tokenizer.model").takeIf { it.exists() && it.canRead() && it.length() > 50_000L },
            if (extFilesDir != null) File(extFilesDir, "tokenizer.model").takeIf { it.exists() && it.canRead() && it.length() > 50_000L } else null
        )
        var chosenTokenizer = candidateTokenizers.firstOrNull()

        // 3. Fallback to /data/local/tmp (Android 14 SELinux check: only if canRead() is permitted)
        if (chosenModel == null) {
            try {
                val tmp = File("/data/local/tmp/llama-3.2-1b-spinquant.pte")
                if (tmp.exists() && tmp.canRead() && tmp.length() > 50_000_000L) {
                    chosenModel = tmp
                }
            } catch (ignored: Throwable) {}
        }
        if (chosenTokenizer == null) {
            try {
                val tmp = File("/data/local/tmp/tokenizer.model")
                if (tmp.exists() && tmp.canRead() && tmp.length() > 50_000L) {
                    chosenTokenizer = tmp
                }
            } catch (ignored: Throwable) {}
        }

        if (chosenModel != null && chosenTokenizer != null) {
            modelFile = chosenModel
            tokenizerFile = chosenTokenizer
            Log.i(TAG, "Located Llama 3.2 1B: model=${chosenModel.absolutePath} (${chosenModel.length() / (1024 * 1024)} MB), tok=${chosenTokenizer.absolutePath}")
            return
        }

        modelFile = null
        tokenizerFile = null
        Log.i(TAG, "Llama 3.2 1B weights not found in storage. Active advisor mode: OFFLINE_GUIDE.")
    }

    private fun isEmulator(): Boolean {
        return (Build.FINGERPRINT.startsWith("generic")
                || Build.FINGERPRINT.startsWith("unknown")
                || Build.MODEL.contains("google_sdk")
                || Build.MODEL.contains("Emulator")
                || Build.MODEL.contains("Android SDK built for x86")
                || Build.MANUFACTURER.contains("Genymotion")
                || (Build.BRAND.startsWith("generic") && Build.DEVICE.startsWith("generic"))
                || "google_sdk" == Build.PRODUCT
                || Build.HARDWARE.contains("goldfish")
                || Build.HARDWARE.contains("ranchu"))
    }

    private fun checkMemoryBudget(): Boolean {
        val sufficient = if (isModelLoaded && llamaModule != null) {
            MemoryBudgetDecider.isMemorySufficientForExecution(context)
        } else {
            MemoryBudgetDecider.isMemorySufficient(context, memoryThresholdBytes)
        }
        if (!sufficient) {
            _isLowMemoryFallback = true
            Log.w(TAG, "Low device RAM. Fallback to KB text alone with label 'Offline guide' (Rule H15).")
        }
        return sufficient
    }

    private fun ensureModelLoaded(): Boolean {
        synchronized(modelLock) {
            if (isModelLoaded && llamaModule != null) {
                return true
            }

            val mFile = modelFile ?: return false
            val tFile = tokenizerFile ?: return false

            if (!checkMemoryBudget()) {
                return false
            }

            try {
                isLoading = true
                val threadName = Thread.currentThread().name
                val threadId = Thread.currentThread().id
                val availMb = MemoryBudgetDecider.getAvailableRamBytes(context) / (1024 * 1024)
                Log.i("CROPDOC_LLAMA", "MODEL_LOAD_START: thread='$threadName' (id=$threadId) availRamMb=${availMb}MB model='${mFile.absolutePath}'")
                Log.i(TAG, "Loading Llama 3.2 1B ExecuTorch module (arm64-v8a): model=${mFile.absolutePath}, tok=${tFile.absolutePath}...")
                val startTime = System.currentTimeMillis()
                val module = LlmModule(mFile.absolutePath, tFile.absolutePath, 0.7f)
                val status = module.load()
                val loadDurationMs = System.currentTimeMillis() - startTime
                val pssMb = Debug.getPss() / 1024L
                Log.i("CROPDOC_LLAMA", "MODEL_LOAD_END: status=$status durationMs=${loadDurationMs}ms thread='$threadName' pssMb=${pssMb}MB")
                Log.i(TAG, "LlamaModule.load() returned status $status in ${loadDurationMs} ms")

                if (status == 0) {
                    llamaModule = module
                    isModelLoaded = true
                    _isLowMemoryFallback = false
                    scheduleIdleRelease()
                    (context.applicationContext as? com.cropdoctor.CropDoctorApplication)?.classifier?.invalidateModule()
                    return true
                } else {
                    Log.e(TAG, "LlamaModule.load() failed with code $status")
                    return false
                }
            } catch (e: Throwable) {
                Log.e(TAG, "Failed to instantiate or load LlamaModule: ${e.message}", e)
                return false
            } finally {
                isLoading = false
            }
        }
    }

    private fun releaseModelInternal(reason: String) {
        if (isGenerating || isLoading) {
            Log.w(TAG, "Cannot release model while isGenerating=$isGenerating or isLoading=$isLoading ($reason)")
            return
        }
        synchronized(modelLock) {
            if (isGenerating || isLoading) return
            try {
                idleJob?.cancel()
                try {
                    llamaModule?.stop()
                } catch (_: Throwable) {}
                try {
                    llamaModule?.resetNative()
                } catch (_: Throwable) {}
                llamaModule = null
                isModelLoaded = false
                System.gc()
                val pssMb = Debug.getPss() / 1024L
                val threadName = Thread.currentThread().name
                Log.i("CROPDOC_LLAMA", "MODEL_RELEASE: reason='$reason' thread='$threadName' pssMb=${pssMb}MB")
                Log.i(TAG, "Released Llama 3.2 1B model ($reason).")
            } catch (e: Throwable) {
                Log.e(TAG, "Error releasing LlamaModule: $reason", e)
            }
        }
    }

    private fun scheduleIdleRelease() {
        idleJob?.cancel()
        idleJob = CoroutineScope(Dispatchers.Default).launch {
            delay(60_000L) // 60 seconds idle release (Rule H15)
            releaseModelInternal("60s_idle_timeout")
        }
    }

    override suspend fun generateAdvice(
        classId: String,
        severityBand: SeverityBand,
        certainty: String,
        language: String,
        kbEntry: KbEntry,
        fieldSpread: String,
        region: String,
        urgency: RulesEngine.UrgencyLevel?,
        crop: String?,
        requestId: Long,
        onToken: (String) -> Unit
    ) = withContext(llamaDispatcher) {
        generationLock.withLock {
            isStopRequested = false
            currentActiveRequestId = requestId
            try {
                generateAdviceInternal(
                    classId = classId,
                    severityBand = severityBand,
                    certainty = certainty,
                    language = language,
                    kbEntry = kbEntry,
                    fieldSpread = fieldSpread,
                    region = region,
                    urgency = urgency,
                    crop = crop,
                    requestId = requestId,
                    onToken = onToken
                )
            } finally {
                if (currentActiveRequestId == requestId) {
                    currentActiveRequestId = -1L
                }
            }
        }
    }

    private suspend fun generateAdviceInternal(
        classId: String,
        severityBand: SeverityBand,
        certainty: String,
        language: String,
        kbEntry: KbEntry,
        fieldSpread: String,
        region: String,
        urgency: RulesEngine.UrgencyLevel?,
        crop: String?,
        requestId: Long,
        onToken: (String) -> Unit
    ) {
        val certaintyBand = when (certainty.uppercase()) {
            "SURE" -> CertaintyBand.SURE
            "PROBABLY" -> CertaintyBand.PROBABLY
            else -> CertaintyBand.NOT_SURE
        }

        val spreadEnum = when (fieldSpread.lowercase()) {
            "few_plants", "a few plants", "few" -> RulesEngine.FieldSpread.FEW_PLANTS
            "most" -> RulesEngine.FieldSpread.MOST
            else -> RulesEngine.FieldSpread.SOME
        }

        val resolvedUrgency = urgency ?: RulesEngine.calculateUrgency(severityBand, spreadEnum)
        val isNotSure = certaintyBand == CertaintyBand.NOT_SURE || classId.equals("unknown", ignoreCase = true)
        val effectiveCrop = crop ?: kbEntry.crop

        // Helper to emit static offline guide immediately in one shot (Rule H11 / Task A-REAL: zero simulated streaming)
        fun emitStaticOfflineGuide(): String {
            _advisorSource = "OFFLINE_GUIDE"
            _isFallbackToOfflineGuide = true
            val staticText = RulesEngine.buildCaseSpecificAdvisory(
                classId = classId,
                crop = effectiveCrop,
                diseaseName = kbEntry.names.forLanguage(language),
                type = kbEntry.type,
                severityBand = severityBand,
                certaintyBand = certaintyBand,
                fieldSpread = spreadEnum,
                urgencyLevel = resolvedUrgency,
                region = region,
                language = language,
                kbEntry = kbEntry
            )
            val cleanStaticText = GuardrailFilter.sanitize(staticText)
            onToken(cleanStaticText)
            Log.i("CROPDOC_DECISION", "ADVISOR_COMPLETE: advisor_source=OFFLINE_GUIDE tokens=0 ttft=0ms tok_per_sec=0.00")
            return cleanStaticText
        }

        // RULE H11 & T2c: When certainty is Not sure or disease unknown, NEVER ask Llama to reason about severity.
        if (isNotSure) {
            Log.i(TAG, "Certainty is Not sure -> routing directly to static offline guide (Task A-REAL)")
            emitStaticOfflineGuide()
            return
        }

        // RULE H6: Telugu is NEVER generated by Llama (Llama 3.2 does not officially support Telugu).
        if (language.equals("te", ignoreCase = true)) {
            Log.i(TAG, "Language is Telugu -> routing directly to verified KB text in code (Rule H6)")
            emitStaticOfflineGuide()
            return
        }

        // Check memory budget before attempting model load
        if (!checkMemoryBudget()) {
            Log.w(TAG, "Memory budget insufficient -> routing directly to static offline guide")
            emitStaticOfflineGuide()
            return
        }

        if (modelFile == null || tokenizerFile == null) {
            findModelFiles()
        }

        // If weights not installed on device
        if (modelFile == null || tokenizerFile == null) {
            Log.i(TAG, "Llama weights not available (model=${modelFile != null}) -> showing static offline guide")
            emitStaticOfflineGuide()
            return
        }

        // Load real Llama 3.2 1B module on Arm phone
        val ready = ensureModelLoaded()
        if (isStopRequested || currentActiveRequestId != requestId) {
            Log.i("CROPDOC_LLAMA", "ADVISORY_ABORT_PRE_GEN: cancelled during model load for requestId=$requestId")
            emitStaticOfflineGuide()
            return
        }
        if (!ready || llamaModule == null) {
            Log.w(TAG, "Real Llama module could not be loaded; falling back to static offline guide")
            emitStaticOfflineGuide()
            return
        }

        // Reset idle release timer
        scheduleIdleRelease()

        // Build case-specific grounded prompt adhering to Task A2
        val prompt = PromptBuilder.buildPrompt(
            crop = effectiveCrop,
            diseaseName = kbEntry.names.forLanguage(language),
            severity = severityBand.name,
            certainty = certainty,
            kbEntry = kbEntry,
            language = language,
            fieldSpread = fieldSpread,
            region = region,
            urgency = resolvedUrgency.name.replace("_", " ")
        )

        val maxNewTokens = 260
        val totalSeqLimit = 768
        val promptApproxTokens = (prompt.length / 3.8).toInt().coerceAtLeast(1)
        val startThreadName = Thread.currentThread().name
        Log.i("CROPDOC_LLAMA", "GEN_START: requestId=$requestId promptTokens=$promptApproxTokens maxNewTokens=$maxNewTokens totalSeqLimit=$totalSeqLimit promptChars=${prompt.length} thread='$startThreadName' (id=${Thread.currentThread().id}) dispatcher=CropDoc-LlamaWorker")

        _advisorSource = "LLAMA"
        _isFallbackToOfflineGuide = false

        val fullTextBuilder = java.lang.StringBuilder()
        var lastEmitTime = System.currentTimeMillis()
        val genStartTime = System.currentTimeMillis()
        var firstTokenTimeMs = 0L
        var totalTokens = 0
        var hitEos = false
        var hitTargetLimit = false
        var lastLoggedTokenCount = 0

        val llamaCallback = object : LlmCallback {
            override fun onResult(token: String?) {
                if (token.isNullOrEmpty()) return
                if (hitEos || hitTargetLimit) return
                if (currentActiveRequestId != requestId) {
                    // Late token from cancelled generation -> stop native loop and ignore
                    stop("cancelled_req${requestId}_current$currentActiveRequestId")
                    return
                }

                // Enforce EOS immediately: do NOT append or emit special tokens
                if (token.contains("<|")) {
                    hitEos = true
                    stop("eos_token")
                    return
                }

                totalTokens++
                val now = System.currentTimeMillis()
                if (firstTokenTimeMs == 0L) {
                    firstTokenTimeMs = now - genStartTime
                }

                val sanitizedToken = GuardrailFilter.sanitize(token)
                fullTextBuilder.append(sanitizedToken)

                if (totalTokens % 20 == 0 && totalTokens != lastLoggedTokenCount) {
                    lastLoggedTokenCount = totalTokens
                    val elapsed = now - genStartTime
                    Log.i("CROPDOC_LLAMA", "TOKEN_20: requestId=$requestId tokens=$totalTokens elapsedMs=${elapsed}ms thread='${Thread.currentThread().name}' chunk='${sanitizedToken.replace("\n", "\\n")}'")
                }

                // Throttle UI update to ~100 ms or upon line breaks / sentence ends
                if (now - lastEmitTime >= 100L || token.contains("\n") || token.contains("।") || token.contains(".")) {
                    lastEmitTime = now
                    if (currentActiveRequestId == requestId) {
                        onToken(fullTextBuilder.toString())
                    }
                }

                if (totalTokens >= maxNewTokens) {
                    hitTargetLimit = true
                    stop("max_tokens_reached")
                }
            }

            override fun onStats(stats: Float) {
                // Optional native execution statistics
            }
        }

        // Guard against oversized prompts that could exceed KV cache bounds
        if (prompt.length > 1800) {
            Log.w(TAG, "Prompt length (${prompt.length} chars) exceeds safety budget -> routing to static offline guide")
            emitStaticOfflineGuide()
            return
        }

        var endReason = "EOS"
        var genException: Throwable? = null

        if (isStopRequested || currentActiveRequestId != requestId) {
            Log.i("CROPDOC_LLAMA", "ADVISORY_ABORT_PRE_GEN: cancelled before gen for requestId=$requestId")
            emitStaticOfflineGuide()
            return
        }

        try {
            isGenerating = true
            val completedInTime = withTimeoutOrNull(75_000L) {
                try {
                    com.cropdoctor.vision.ExecuTorchLock.mutex.withLock {
                        if (!isGenerating || currentActiveRequestId != requestId) {
                            return@withLock null
                        }
                        llamaModule?.generate(prompt, totalSeqLimit, llamaCallback, false)
                    }
                } catch (t: Throwable) {
                    genException = t
                    Log.e(TAG, "Native Llama generate failed, falling back to offline guide", t)
                    null
                }
            }

            endReason = when {
                hitEos -> "EOS"
                hitTargetLimit -> "token limit"
                totalTokens + promptApproxTokens >= 760 -> "token limit"
                completedInTime == null && genException == null -> "timeout"
                genException != null -> "error"
                else -> "EOS"
            }

            val rawGeneratedText = fullTextBuilder.toString().trim()
            val (cleanText, wasCut) = SentenceTrimmer.cleanToCompleteSentence(rawGeneratedText, language)

            val finalFullText = if (wasCut || hitTargetLimit || endReason != "EOS" || completedInTime == null) {
                val remainingSections = RulesEngine.buildRemainingSections(
                    trimmedText = cleanText,
                    classId = classId,
                    crop = effectiveCrop,
                    diseaseName = kbEntry.names.forLanguage(language),
                    type = kbEntry.type,
                    severityBand = severityBand,
                    certaintyBand = certaintyBand,
                    fieldSpread = spreadEnum,
                    urgencyLevel = resolvedUrgency,
                    region = region,
                    language = language,
                    kbEntry = kbEntry
                )
                if (cleanText.isNotEmpty()) {
                    if (remainingSections.isNotEmpty()) {
                        "$cleanText\n\n---\n[Offline guide - Additional steps]\n$remainingSections"
                    } else {
                        cleanText
                    }
                } else {
                    RulesEngine.buildCaseSpecificAdvisory(
                        classId = classId,
                        crop = effectiveCrop,
                        diseaseName = kbEntry.names.forLanguage(language),
                        type = kbEntry.type,
                        severityBand = severityBand,
                        certaintyBand = certaintyBand,
                        fieldSpread = spreadEnum,
                        urgencyLevel = resolvedUrgency,
                        region = region,
                        language = language,
                        kbEntry = kbEntry
                    )
                }
            } else {
                cleanText
            }

            // Update UI with sentence-complete text
            if (currentActiveRequestId == requestId) {
                onToken(finalFullText)
            }

            val totalGenDurationMs = System.currentTimeMillis() - genStartTime

            // Verify with GuardrailFilter (Rule H4, H5 & Task A2)
            val validation = GuardrailFilter.validateAdvice(
                generatedText = finalFullText,
                kbEntry = kbEntry,
                severityBand = severityBand,
                urgencyLevel = resolvedUrgency,
                certaintyBand = certaintyBand
            )
            if (!validation.isValid) {
                Log.w(TAG, "Guardrail violation: ${validation.failureReason}. Reverting to verified KB text alone (Offline guide).")
                _advisorSource = "OFFLINE_GUIDE"
                _isFallbackToOfflineGuide = true
                val officialKbText = "\n\n" + RulesEngine.buildCaseSpecificAdvisory(
                    classId = classId,
                    crop = effectiveCrop,
                    diseaseName = kbEntry.names.forLanguage(language),
                    type = kbEntry.type,
                    severityBand = severityBand,
                    certaintyBand = certaintyBand,
                    fieldSpread = spreadEnum,
                    urgencyLevel = resolvedUrgency,
                    region = region,
                    language = language,
                    kbEntry = kbEntry
                )
                onToken(officialKbText)
                Log.i("CROPDOC_DECISION", "ADVISOR_COMPLETE: advisor_source=OFFLINE_GUIDE tokens=$totalTokens ttft=${firstTokenTimeMs}ms tok_per_sec=0.00")
                return
            }

            val genOnlyMs = totalGenDurationMs - firstTokenTimeMs
            val tokensPerSec = if (genOnlyMs > 0) (totalTokens.toDouble() / (genOnlyMs / 1000.0)) else 0.0
            val currentThreads = ExecuTorchNativeThreadHelper.getThreadNum()

            Log.i("CROPDOC_LLAMA", "GEN_METRICS: requestId=$requestId promptTokens=$promptApproxTokens maxNewTokens=$maxNewTokens totalSeqLimit=$totalSeqLimit tokensProduced=$totalTokens ttftMs=$firstTokenTimeMs tokPerSec=${String.format(Locale.US, "%.2f", tokensPerSec)} threads=$currentThreads endReason='$endReason'")
            Log.i("CROPDOC_DECISION", "ADVISOR_COMPLETE: advisor_source=LLAMA tokens=$totalTokens ttft=${firstTokenTimeMs}ms tok_per_sec=${String.format(Locale.US, "%.2f", tokensPerSec)} threads=$currentThreads")

            logBenchmarkMetrics(
                loadTimeMs = 0L,
                firstTokenTimeMs = firstTokenTimeMs,
                totalGenTimeMs = totalGenDurationMs,
                tokenCount = totalTokens,
                language = language,
                crop = effectiveCrop,
                disease = kbEntry.names.en,
                guardrailPassed = validation.isValid
            )

        } catch (ce: CancellationException) {
            endReason = "cancelled"
            throw ce
        } catch (e: Exception) {
            endReason = "error: ${e.message}"
            Log.e(TAG, "Error during Llama generation", e)
            emitStaticOfflineGuide()
        } finally {
            isGenerating = false
            val totalGenDurationMs = System.currentTimeMillis() - genStartTime
            Log.i("CROPDOC_LLAMA", "GEN_END: requestId=$requestId reason='$endReason' totalTokens=$totalTokens durationMs=${totalGenDurationMs}ms thread='${Thread.currentThread().name}' dispatcher=CropDoc-LlamaWorker")
        }
    }

    private fun logBenchmarkMetrics(
        loadTimeMs: Long,
        firstTokenTimeMs: Long,
        totalGenTimeMs: Long,
        tokenCount: Int,
        language: String,
        crop: String,
        disease: String,
        guardrailPassed: Boolean
    ) {
        try {
            val genOnlyMs = totalGenTimeMs - firstTokenTimeMs
            val tokensPerSec = if (genOnlyMs > 0) (tokenCount.toDouble() / (genOnlyMs / 1000.0)) else 0.0
            val peakRamPssMb = Debug.getPss() / 1024L

            val dateFormat = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US)
            val dateStr = dateFormat.format(Date())

            val benchDir = File(context.filesDir, "benchmarks")
            benchDir.mkdirs()

            val logFile = File(benchDir, "llama_$dateStr.json")
            val latestFile = File(benchDir, "llama_latest.json")

            val jsonContent = """
{
  "timestamp": "$dateStr",
  "device_model": "${Build.MODEL}",
  "cpu_abi": "${Build.SUPPORTED_ABIS.firstOrNull() ?: "unknown"}",
  "target_hardware": "Arm64-v8a",
  "model_name": "meta-llama/Llama-3.2-1B-Instruct",
  "quantization": "SpinQuant INT4 EO8",
  "runtime": "ExecuTorch 0.6.0",
  "advisor_source": "LLAMA",
  "crop": "$crop",
  "disease": "$disease",
  "language": "$language",
  "metrics": {
    "first_token_time_ms": $firstTokenTimeMs,
    "total_generation_time_ms": $totalGenTimeMs,
    "tokens_generated": $tokenCount,
    "tokens_per_second": ${String.format(Locale.US, "%.2f", tokensPerSec)},
    "peak_ram_pss_mb": $peakRamPssMb,
    "ram_budget_limit_mb": 2500,
    "ram_budget_compliant": ${peakRamPssMb <= 2500},
    "guardrail_passed": $guardrailPassed
  }
}
            """.trimIndent()

            logFile.writeText(jsonContent)
            latestFile.writeText(jsonContent)
            Log.i(TAG, "Benchmark logged to ${logFile.absolutePath} (Tokens/s: ${String.format(Locale.US, "%.2f", tokensPerSec)}, RAM: ${peakRamPssMb}MB)")
        } catch (e: Exception) {
            Log.e(TAG, "Failed to write llama benchmark log", e)
        }
    }

    override suspend fun answerChatPrompt(prompt: String): String = withContext(llamaDispatcher) {
        generationLock.withLock {
            val chatRequestId = System.nanoTime()
            isStopRequested = false
            currentActiveRequestId = chatRequestId
            val maxNewTokens = 80
            val totalSeqLimit = 512
            val promptApproxTokens = (prompt.length / 3.8).toInt().coerceAtLeast(1)
            val startThreadName = Thread.currentThread().name
            Log.i("CROPDOC_LLAMA", "CHAT_GEN_START: requestId=$chatRequestId promptTokens=$promptApproxTokens maxNewTokens=$maxNewTokens totalSeqLimit=$totalSeqLimit promptChars=${prompt.length} thread='$startThreadName' dispatcher=CropDoc-LlamaWorker")

            if (!checkMemoryBudget()) {
                Log.w(TAG, "Memory budget insufficient for chat answer")
                if (currentActiveRequestId == chatRequestId) currentActiveRequestId = -1L
                return@withContext ""
            }

            val ready = ensureModelLoaded()
            if (isStopRequested || currentActiveRequestId != chatRequestId) {
                if (currentActiveRequestId == chatRequestId) currentActiveRequestId = -1L
                return@withContext ""
            }
            if (!ready || llamaModule == null) {
                Log.w(TAG, "Real Llama module could not be loaded for chat answer")
                if (currentActiveRequestId == chatRequestId) currentActiveRequestId = -1L
                return@withContext ""
            }

            scheduleIdleRelease()
            val responseBuilder = StringBuilder()
            var totalTokens = 0
            val genStartTime = System.currentTimeMillis()
            var firstTokenTimeMs = 0L
            var hitEos = false
            var hitTargetLimit = false

            val callback = object : LlmCallback {
                override fun onResult(token: String?) {
                    if (token.isNullOrEmpty()) return
                    if (hitEos || hitTargetLimit) return
                    if (currentActiveRequestId != chatRequestId) {
                        stop("cancelled_chat_req${chatRequestId}_current$currentActiveRequestId")
                        return
                    }
                    totalTokens++
                    val now = System.currentTimeMillis()
                    if (firstTokenTimeMs == 0L) {
                        firstTokenTimeMs = now - genStartTime
                    }
                    if (token.contains("<|")) {
                        hitEos = true
                        stop("chat_eos")
                        return
                    }
                    val sanitizedToken = GuardrailFilter.sanitize(token)
                    responseBuilder.append(sanitizedToken)
                    if (totalTokens >= maxNewTokens || responseBuilder.length >= 400) {
                        hitTargetLimit = true
                        stop("chat_complete_or_cap")
                    }
                }
                override fun onStats(stats: Float) {}
            }

            var chatException: Throwable? = null
            var endReason = "EOS"
            try {
                isGenerating = true
                val completed = withTimeoutOrNull(30_000L) {
                    try {
                        com.cropdoctor.vision.ExecuTorchLock.mutex.withLock {
                            if (!isGenerating || currentActiveRequestId != chatRequestId) {
                                return@withLock null
                            }
                            llamaModule?.generate(prompt, totalSeqLimit, callback, false)
                        }
                    } catch (e: Exception) {
                        chatException = e
                        Log.e(TAG, "Error generating chat answer: ${e.message}", e)
                        null
                    }
                }
                endReason = when {
                    hitEos -> "EOS"
                    hitTargetLimit -> "token limit"
                    completed == null && chatException == null -> "timeout"
                    chatException != null -> "error"
                    else -> "EOS"
                }
            } catch (ce: CancellationException) {
                endReason = "cancelled"
                throw ce
            } finally {
                isGenerating = false
                val totalGenDurationMs = System.currentTimeMillis() - genStartTime
                val genOnlyMs = totalGenDurationMs - firstTokenTimeMs
                val chatTokPerSec = if (genOnlyMs > 0) (totalTokens.toDouble() / (genOnlyMs / 1000.0)) else 0.0
                Log.i("CROPDOC_LLAMA", "CHAT_GEN_METRICS: requestId=$chatRequestId promptTokens=$promptApproxTokens maxNewTokens=$maxNewTokens totalSeqLimit=$totalSeqLimit tokensProduced=$totalTokens ttftMs=$firstTokenTimeMs tokPerSec=${String.format(Locale.US, "%.2f", chatTokPerSec)} durationMs=$totalGenDurationMs endReason='$endReason'")
                Log.i("CROPDOC_LLAMA", "CHAT_GEN_END: requestId=$chatRequestId reason='$endReason' totalTokens=$totalTokens durationMs=${totalGenDurationMs}ms thread='${Thread.currentThread().name}' dispatcher=CropDoc-LlamaWorker")
                if (currentActiveRequestId == chatRequestId) {
                    currentActiveRequestId = -1L
                }
            }
            val rawChat = responseBuilder.toString().trim()
            val (cleanChat, _) = SentenceTrimmer.cleanToCompleteSentence(rawChat)
            return@withContext if (cleanChat.isNotBlank()) cleanChat else rawChat
        }
    }

    override fun stop() {
        stop("unspecified")
    }

    override fun stop(reason: String) {
        val callerThread = Thread.currentThread().name
        Log.i("CROPDOC_LLAMA", "STOP_CALLED: reason='$reason' callerThread='$callerThread'")
        isStopRequested = true
        currentActiveRequestId = -1L
        if (isGenerating || isLoading) {
            try {
                llamaModule?.stop()
                Log.i(TAG, "LlamaModule.stop() requested ($reason)")
            } catch (e: Throwable) {
                Log.e(TAG, "Failed to stop LlamaModule", e)
            }
        }
    }

    override suspend fun cancelAndAwait(timeoutMs: Long): Boolean {
        val callerThread = Thread.currentThread().name
        Log.i("CROPDOC_LLAMA", "CANCEL_AWAIT_START: timeoutMs=${timeoutMs}ms callerThread='$callerThread' isGenerating=$isGenerating isLoading=$isLoading activeRequestId=$currentActiveRequestId")
        if (!isGenerating && !isLoading) {
            return true
        }
        stop("cancelAndAwait")
        return try {
            withTimeout(timeoutMs) {
                while (isGenerating || isLoading) {
                    delay(30L)
                }
            }
            Log.i("CROPDOC_LLAMA", "CANCEL_AWAIT_SUCCESS: Llama stopped and returned cleanly")
            true
        } catch (e: TimeoutCancellationException) {
            Log.w("CROPDOC_LLAMA", "CANCEL_AWAIT_TIMEOUT: Llama did not return within ${timeoutMs}ms")
            false
        }
    }

    override fun close() {
        releaseModelInternal("advisor_close")
    }

