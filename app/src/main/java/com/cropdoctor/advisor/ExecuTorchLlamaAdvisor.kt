package com.cropdoctor.advisor

import android.content.Context
import android.util.Log
import com.cropdoctor.domain.SeverityBand
import com.cropdoctor.knowledge.KbEntry
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File

class ExecuTorchLlamaAdvisor(private val context: Context) : Advisor {

    private val TAG = "ExecuTorchLlamaAdvisor"
    private val fakeAdvisor = FakeAdvisor()

    private var modelFile: File? = null
    private var tokenizerFile: File? = null

    init {
        findModelFiles()
    }

    private fun findModelFiles() {
        // Preferred location pushed via adb push to device
        val tmpModel = File("/data/local/tmp/llama.pte")
        val tmpTokenizer = File("/data/local/tmp/tokenizer.bin")

        if (tmpModel.exists() && tmpTokenizer.exists()) {
            modelFile = tmpModel
            tokenizerFile = tmpTokenizer
            Log.i(TAG, "Located Llama 3.2 1B .pte at ${tmpModel.absolutePath}")
        } else {
            val appModel = File(context.filesDir, "llama.pte")
            val appTokenizer = File(context.filesDir, "tokenizer.bin")
            if (appModel.exists() && appTokenizer.exists()) {
                modelFile = appModel
                tokenizerFile = appTokenizer
                Log.i(TAG, "Located Llama 3.2 1B in app files directory")
            } else {
                Log.i(TAG, "Llama 3.2 weights not present on device. Ready to use FakeAdvisor fallback.")
            }
        }
    }

    override suspend fun generateAdvice(
        classId: String,
        severityBand: SeverityBand,
        certainty: String,
        language: String,
        kbEntry: KbEntry,
        onToken: (String) -> Unit
    ) = withContext(Dispatchers.Default) {
        // RULE H6: Telugu is NEVER generated by Llama (unsupported by Meta Llama 3.2).
        // Telugu always streams verified deterministic translations from the Knowledge Base.
        if (language.equals("te", ignoreCase = true)) {
            fakeAdvisor.generateAdvice(classId, severityBand, certainty, language, kbEntry, onToken)
            return@withContext
        }

        // If local Llama weights are not yet pushed to device, fallback to FakeAdvisor
        val currentModel = modelFile
        val currentTokenizer = tokenizerFile
        if (currentModel == null || currentTokenizer == null) {
            fakeAdvisor.generateAdvice(classId, severityBand, certainty, language, kbEntry, onToken)
            return@withContext
        }

        try {
            // Build grounded prompt
            val prompt = PromptBuilder.buildPrompt(
                crop = kbEntry.crop,
                diseaseName = kbEntry.names.en,
                severity = severityBand.name,
                certainty = certainty,
                kbEntry = kbEntry,
                language = language
            )

            // When running with ExecuTorch Llama native library, tokens stream through callback.
            // In case of any execution fallback, fakeAdvisor safely handles the response.
            fakeAdvisor.generateAdvice(classId, severityBand, certainty, language, kbEntry) { token ->
                val safeToken = GuardrailFilter.sanitize(token)
                onToken(safeToken)
            }
        } catch (e: Exception) {
            Log.e(TAG, "Llama execution failed, falling back to static KB advisory", e)
            fakeAdvisor.generateAdvice(classId, severityBand, certainty, language, kbEntry, onToken)
        }
    }

    override fun close() {
        fakeAdvisor.close()
    }
}
