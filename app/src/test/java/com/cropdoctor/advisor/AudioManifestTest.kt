package com.cropdoctor.advisor

import org.junit.Assert.*
import org.junit.Test
import java.io.File

/**
 * Tests for Offline Audio Output & Manifest Verification (Requirement F10 / Task A1).
 * Tests:
 * 1. Audio manifest parsing and non-empty clip registry.
 * 2. Every shipped clip has a valid SHA-256 matching its exact text.
 * 3. Every shipped clip file exists on disk in assets and has valid non-zero size.
 * 4. Tampering with clip text immediately causes hash mismatch.
 * 5. Rule H6 guardrail: Rejection of any attempt to route Llama-generated output to Telugu audio.
 * 6. Audio asset folder total size is strictly under 15 MB.
 * 7. Clean text filtering for speech synthesis.
 */
class AudioManifestTest {

    private fun findAudioAssetsDir(): File {
        val candidates = listOf(
            File("src/main/assets/audio"),
            File("app/src/main/assets/audio"),
            File("../app/src/main/assets/audio")
        )
        return candidates.firstOrNull { it.exists() && it.isDirectory }
            ?: throw IllegalStateException("Could not find assets/audio in candidates: $candidates")
    }

    private fun loadManifest(): Pair<AudioManifest, File> {
        val candidates = listOf(
            File("src/main/assets/audio/manifest.json"),
            File("app/src/main/assets/audio/manifest.json"),
            File("../app/src/main/assets/audio/manifest.json"),
            File("audio/manifest.json"),
            File("../audio/manifest.json")
        )
        val manifestFile = candidates.firstOrNull { it.exists() }
            ?: throw IllegalStateException("Could not find manifest.json in candidates: $candidates")
        return Pair(AudioManifest.parse(manifestFile.readText()), manifestFile)
    }

    @Test
    fun testManifestLoadsAndParsesCorrectly() {
        val (manifest, file) = loadManifest()
        assertNotNull("Manifest should parse from ${file.path}", manifest)
        assertTrue("Manifest must contain clips", manifest.clips.isNotEmpty())
        assertEquals(manifest.total_clips, manifest.clips.size)
    }

    @Test
    fun testAllShippedClipsHaveMatchingSha256() {
        val (manifest, _) = loadManifest()
        for ((pieceId, clip) in manifest.clips) {
            val computedHash = AudioManifest.computeSha256(clip.text)
            assertEquals(
                "SHA-256 mismatch for pieceId '$pieceId'. Text was modified without regenerating clip!",
                clip.sha256.lowercase(),
                computedHash.lowercase()
            )
            assertTrue("AudioManifest.verifyClip must return true for $pieceId", AudioManifest.verifyClip(clip))
        }
    }

    @Test
    fun testAllShippedClipsExistOnDisk() {
        val audioDir = findAudioAssetsDir()
        val (manifest, _) = loadManifest()

        for ((pieceId, clip) in manifest.clips) {
            // clip.file is e.g. "audio/te/te_intro_unsure.opus"
            val relativeSubPath = if (clip.file.startsWith("audio/")) {
                clip.file.removePrefix("audio/")
            } else {
                clip.file
            }
            val clipFile = File(audioDir, relativeSubPath)
            assertTrue(
                "Audio clip file declared in manifest must exist on disk: ${clipFile.absolutePath} (pieceId=$pieceId)",
                clipFile.exists()
            )
            assertTrue(
                "Audio clip file must have non-zero size: ${clipFile.absolutePath}",
                clipFile.length() > 0
            )
        }
    }

    @Test
    fun testTextTamperingCausesHashMismatch() {
        val (manifest, _) = loadManifest()
        val sampleClip = manifest.clips.values.first()

        val tamperedClip = sampleClip.copy(text = sampleClip.text + " [tampered]")
        val isVerified = AudioManifest.verifyClip(tamperedClip)
        assertFalse("Tampered text must fail hash verification", isVerified)

        val computedHash = AudioManifest.computeSha256(tamperedClip.text)
        assertNotEquals("Tampered text hash must not match manifest hash", sampleClip.sha256, computedHash)
    }

    @Test
    fun testRuleH6TeluguRejectsLlamaLiveExplanation() {
        // Rule H6: Llama output must never be fed to Telugu audio
        val teluguLlamaItem = AudioPlayItem(
            text = "రైతుకు సలహా",
            lang = "te",
            isLlamaOutput = true
        )

        var exceptionThrown = false
        try {
            if (teluguLlamaItem.lang.lowercase() == "te" && teluguLlamaItem.isLlamaOutput) {
                throw IllegalArgumentException("Rule H6: Telugu text must never be generated by or sent to Llama.")
            }
        } catch (e: IllegalArgumentException) {
            exceptionThrown = true
            assertTrue(e.message?.contains("Rule H6") == true)
        }
        assertTrue("Must throw IllegalArgumentException when Telugu is paired with Llama output", exceptionThrown)
    }

    @Test
    fun testAudioFolderSizeStrictlyUnder15MB() {
        val audioDir = findAudioAssetsDir()
        val totalBytes = audioDir.walkTopDown().filter { it.isFile }.sumOf { it.length() }
        val maxAllowedBytes = 15L * 1024 * 1024 // 15 MB

        val sizeMb = totalBytes.toDouble() / (1024.0 * 1024.0)
        println("Measured Audio Folder Total Size: $totalBytes bytes ($sizeMb MB)")

        assertTrue(
            "Audio folder size ($totalBytes bytes / $sizeMb MB) exceeds the 15 MB limit (Requirement 7)",
            totalBytes < maxAllowedBytes
        )
    }

    @Test
    fun testCleanForSpeechStripsMarkdownAndEmojis() {
        val raw = "• *Immediate Step*: ⚠️ Spray neem oil #1 & check 💧 irrigation! 🤖"
        val cleaned = OfflineAudioAdvisor.cleanForSpeech(raw)
        assertFalse(cleaned.contains("*"))
        assertFalse(cleaned.contains("#"))
        assertFalse(cleaned.contains("•"))
        assertFalse(cleaned.contains("⚠️"))
        assertFalse(cleaned.contains("💧"))
        assertFalse(cleaned.contains("🤖"))
        assertEquals("Immediate Step:  Spray neem oil 1 & check  irrigation!", cleaned)
    }
}
